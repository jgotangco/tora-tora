export function textWidth(text: string, scale = 1): number {
  return text.length * 6 * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const up = text.toUpperCase();
  for (const ch of up) {
    const g = FONT[ch] ?? FONT[" "];
    for (let r = 0; r < 7; r++) {
      const bits = g[r] ?? 0;
      for (let c = 0; c < 5; c++) {
        if (bits & (1 << (4 - c))) {
          ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
        }
      }
    }
    cx += 6 * scale;
  }
}

export function drawTextShadow(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  drawText(ctx, text, x + scale, y + scale, "#07140f", scale);
  drawText(ctx, text, x, y, color, scale);
}
